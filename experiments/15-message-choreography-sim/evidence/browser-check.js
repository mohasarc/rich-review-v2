async (page) => {
  const output = '/Users/moyaseen/projects/rich-review-v2/experiments/15-message-choreography-sim';
  const browser = page.context().browser();
  const existing = browser.contexts().flatMap(context => context.pages()).find(candidate => candidate.url().startsWith('http://127.0.0.1:8715/') || candidate.url().endsWith('15-message-choreography-sim/index.html'));
  const p = existing ?? await (await browser.newContext()).newPage();
  const errors = [];
  const listener = error => errors.push(error.message);
  p.on('pageerror', listener);
  const checks = [];
  const check = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  await p.setViewportSize({ width: 1440, height: 1100 });
  await p.goto('http://127.0.0.1:8715/');
  check(await p.locator('.decision-card').count() === 11, 'All 11 decision summaries are in the opening layer');
  for (const id of ['ownership','deadlines','recovery','output','resources','operations','tests','error','fetch-limit','test-changes','enforcement']) {
    await p.locator(`.decision-card[data-decision="${id}"]`).click();
    check(await p.locator('#inspector').isVisible(), `${id}: detail opens`);
    await p.locator('#inspector [data-ref]').first().click();
    check(await p.locator('#inspector .code-line').count() > 0, `${id}: exact source opens`);
    await p.locator('#inspector-back').click();
    check(await p.locator('#inspector .reason-box').count() === 1, `${id}: source returns to the decision`);
    await p.locator('#inspector-close').click();
  }
  await p.locator('select[name=purpose]').selectOption('ordinary');
  await p.locator('[data-compare=head]').click();
  check(await p.locator('#head-result').textContent() === 'response received', '150 ms ordinary ping responds');
  await p.locator('select[name=purpose]').selectOption('status-observer');
  await p.locator('[data-compare=head]').click();
  check(await p.locator('#head-result').textContent() === 'timeout', 'The same ping times out for status observation');
  await p.locator('select[name=message]').selectOption('execution-status');
  check(await p.locator('select[name=purpose]').isDisabled(), 'Execution-status scene keeps the ordinary composition path');
  await p.locator('[data-compare=head]').click();
  check((await p.locator('#head-meta').textContent()).includes('250 ms'), 'Execution-status uses 250 ms');
  await p.locator('select[name=message]').selectOption('ping');
  await p.locator('#reset').click();
  check(await p.locator('#event-index').textContent() === 'READY', 'Reset returns the tape to ready');
  await p.locator('#send').click();
  await p.waitForFunction(() => !document.querySelector('#event-index').textContent.startsWith('01'));
  await p.locator('#pause').click();
  const paused = await p.locator('#event-index').textContent();
  await p.waitForTimeout(950);
  check(await p.locator('#event-index').textContent() === paused, 'Pause freezes the event cursor');
  await p.locator('#pause').click();
  await p.waitForFunction(previous => document.querySelector('#event-index').textContent !== previous, paused);
  if (await p.locator('#pause').isEnabled()) await p.locator('#pause').click();
  checks.push('Resume advances the cursor');
  await p.locator('#event-tape [data-event="1"]').click();
  await p.locator('#envelope').click();
  check((await p.locator('.envelope-code').first().textContent()).includes('"ping"'), 'Envelope sketch follows the selected event');
  await p.keyboard.press('Escape');
  check(!await p.locator('#inspector').isVisible(), 'Escape closes detail');
  await p.locator('[data-preset=reattach]').click();
  await p.locator('[data-compare=head]').click();
  check((await p.locator('#head-meta').textContent()).includes('2 execute · 1 fetch'), 'Reattached execute gets a fetch resume');
  await p.locator('[data-preset=error]').click();
  await p.locator('[data-compare=head]').click();
  check(await p.locator('#head-result').textContent() === 'corrupt · later error', 'Head shows the later corrupt error');
  check(await p.locator('#base-result').textContent() === 'closed · first error', 'Base shows the earlier closed error');
  await p.locator('[data-preset=fetch]').click();
  await p.locator('[data-compare=head]').click();
  check((await p.locator('#head-meta').textContent()).includes('1 fetch'), 'Two allowed resumes still show one fetch on clean EOF');
  await p.locator('[data-scene=output]').click();
  await p.locator('select[name=profile]').selectOption('miniature');
  await p.locator('[data-compare=head]').click();
  check((await p.locator('#head-meta').textContent()).includes('3 records · disk'), 'Miniature output policy spills six bytes in three records');
  check((await p.locator('#base-meta').textContent()).includes('1 records · inline'), 'Base consumer retains its local output defaults');
  await p.locator('[data-open=sources]').first().click();
  await p.locator('#source-filter').fill('local-daemon-transport');
  check(await p.locator('#source-list button').count() === 5, 'Source filtering finds all five transport paths');
  await p.locator('#source-list button').first().click();
  check(await p.locator('.code-window.patch').count() === 1, 'A changed file opens its exact patch');
  await p.locator('#inspector-close').click();
  await p.locator('[data-open=policy]').click();
  await p.locator('[data-policy-group=delivery]').click();
  check(await p.locator('table').first().locator('tbody tr').count() === 2, 'Policy table filters to the independent delivery limits');
  await p.locator('#inspector-close').click();
  await p.locator('[data-preset=reattach]').click();
  await p.locator('#event-tape button').filter({hasText:'result-fetch'}).click();
  await p.locator('#simulator').evaluate(el => el.scrollIntoView({ block: 'start' }));
  await p.screenshot({path:output+'/screenshots/01-message.png'});
  await p.evaluate(() => scrollTo(0,0));
  await p.screenshot({path:output+'/screenshots/02-opening.png'});
  await p.setViewportSize({ width: 390, height: 844 });
  await p.locator('#simulator').evaluate(el => el.scrollIntoView({ block: 'start' }));
  check(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390 px layout has no horizontal page overflow');
  await p.locator('#event-tape button').last().click();
  check(await p.locator('#head-result').textContent() === 'completed', 'The mobile tape remains interactive');
  await p.locator('.actors-stage').evaluate(el => el.scrollIntoView({ block: 'start' }));
  await p.screenshot({path:output+'/screenshots/03-mobile.png'});
  await p.setViewportSize({ width: 1440, height: 1100 });
  await p.goto('file://'+output+'/index.html');
  await p.locator('#step').click();
  check(await p.locator('#event-title').textContent() === 'Select 100 ms', 'Double-click file entry works without a server');
  check(errors.length === 0, 'No page JavaScript errors');
  p.off('pageerror', listener);
  const report = { recordedAt: new Date().toISOString(), checks, errors };
  return report;
}
