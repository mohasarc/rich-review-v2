import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('/tmp/rich-review-05-browser/node_modules/playwright');
const out = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const browser = await chromium.launch({headless:true, executablePath:'/Users/moyaseen/Library/Caches/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-mac-arm64/chrome-headless-shell'});
const result = {checkedAt:new Date().toISOString(), errors:[], checks:[]};
function check(name, condition, detail){result.checks.push({name, passed:condition, detail}); if(!condition)result.errors.push(name);}
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route(/^https?:/, route=>route.abort());
  const page=await context.newPage();
  page.on('pageerror',e=>result.errors.push(e.message));
  await page.goto('file://'+path.join(out,'index.html'));
  check('All rows initially visible',await page.locator('tbody tr:visible').count()===47);
  await page.screenshot({path:path.join(out,'captures/report-desktop.png')});
  await page.getByLabel('Show').selectOption('flag');
  const ids=await page.locator('tbody tr:visible').evaluateAll(rows=>rows.map(r=>r.id));
  check('Rule-4 filter',JSON.stringify(ids)===JSON.stringify(['row-04','row-23','row-27-131']),ids);
  await page.locator('#comparison').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(out,'captures/report-rule4.png')});
  await page.locator('#row-04 a[href="evidence.html#D1"]').click();
  check('Parent-child evidence navigation',page.url().endsWith('evidence.html#D1'));
  check('Correct textbook destination',await page.locator('#D1').innerText().then(t=>t.includes('4.9')));
  await page.goBack();
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.getByLabel('Find').fill('no_matching_phrase_46');
  check('Empty search state',await page.locator('tbody tr:visible').count()===0 && await page.locator('#empty').isVisible());
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  check('Reset restores full table',await page.locator('tbody tr:visible').count()===47);
  await page.getByLabel('Show').selectOption('correction');
  check('Correction filter includes old-test correction',await page.locator('#row-01-127').isVisible());
  await context.close();
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
  await mobile.route(/^https?:/,route=>route.abort());
  const mp=await mobile.newPage();
  mp.on('pageerror',e=>result.errors.push(e.message));
  await mp.goto('file://'+path.join(out,'index.html'));
  const widths=await mp.evaluate(()=>({document:document.documentElement.scrollWidth,viewport:innerWidth}));
  check('Mobile has no horizontal overflow',widths.document<=widths.viewport,widths);
  await mp.screenshot({path:path.join(out,'captures/report-mobile.png')});
  await mp.getByLabel('Show').selectOption('flag');
  check('Mobile filter',await mp.locator('tbody tr:visible').count()===3);
  await mobile.close();
} finally {await browser.close();}
fs.writeFileSync(path.join(out,'browser-check.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
if(result.errors.length)process.exitCode=1;
